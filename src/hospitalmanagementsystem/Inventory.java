    private void AddItemBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AddItemBtnMouseClicked
        if (ItemIdTb.getText().isEmpty() || ItemNameTb.getText().isEmpty() || StockQuantityTb.getText().isEmpty() || SupplierTb.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Missing Information");
    } else {
        try {
            boolean isItemIdValid = true;
            boolean isStockQuantityValid = true;

            int itemId = 0;
            int stockQuantity = 0;

            // Validare pentru Item ID
            try {
                itemId = Integer.parseInt(ItemIdTb.getText());
            } catch (NumberFormatException e) {
                isItemIdValid = false;
            }

            // Validare pentru Stock Quantity
            try {
                stockQuantity = Integer.parseInt(StockQuantityTb.getText());
            } catch (NumberFormatException e) {
                isStockQuantityValid = false;
            }

            // Gestionam cazurile posibile pentru mesaje de eroare
            if (!isItemIdValid && !isStockQuantityValid) {
                JOptionPane.showMessageDialog(this, "Please enter valid numbers for both Item ID and Stock Quantity.");
                return;
            } else if (!isItemIdValid) {
                JOptionPane.showMessageDialog(this, "Please enter a valid number for Item ID.");
                return;
            } else if (!isStockQuantityValid) {
                JOptionPane.showMessageDialog(this, "Please enter a valid number for Stock Quantity.");
                return;
            }

            // Conectare la baza de date
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

            // Verificam daca obiectul exista deja
            String CheckQuery = "SELECT * FROM inventory WHERE item_id = ?";
            PreparedStatement CheckStmt = Con.prepareStatement(CheckQuery);
            CheckStmt.setInt(1, itemId);
            Rs = CheckStmt.executeQuery();

            if (Rs.next()) {
                JOptionPane.showMessageDialog(this, "Item with this ID already exists. Use Update to modify it.");
            } else {
                // Inseram un nou obiect in baza de date
                String InsertQuery = "INSERT INTO inventory (item_id, item_name, item_type, stock_quantity, location, supplier) VALUES (?, ?, ?, ?, ?, ?)";
                PreparedStatement Add = Con.prepareStatement(InsertQuery);
                Add.setInt(1, itemId);
                Add.setString(2, ItemNameTb.getText());
                Add.setString(3, ItemTypeCb.getSelectedItem().toString());
                Add.setInt(4, stockQuantity);
                Add.setString(5, LocationCb.getSelectedItem().toString());
                Add.setString(6, SupplierTb.getText());

                int row = Add.executeUpdate();
                JOptionPane.showMessageDialog(this, "Item Added Successfully");

                // Reimprospatam tabelul și golim campurile
                DisplayInventory();
                Clear();
            }
            Con.close();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    }//GEN-LAST:event_AddItemBtnMouseClicked

    private void UpdateItemBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_UpdateItemBtnMouseClicked
        if (Key == 0) {
        JOptionPane.showMessageDialog(this, "Select an Item to Update");
    } else {
        try {
            int stockQuantity = Integer.parseInt(StockQuantityTb.getText());
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");
            String UpdateQuery = "UPDATE inventory SET item_name = ?, item_type = ?, stock_quantity = ?, location = ?, supplier = ? WHERE item_id = ?";
            PreparedStatement Update = Con.prepareStatement(UpdateQuery);
            Update.setString(1, ItemNameTb.getText());
            Update.setString(2, ItemTypeCb.getSelectedItem().toString());
            Update.setInt(3, stockQuantity);
            Update.setString(4, LocationCb.getSelectedItem().toString());
            Update.setString(5, SupplierTb.getText());
            Update.setInt(6, Key);
            int row = Update.executeUpdate();
            JOptionPane.showMessageDialog(this, "Item Updated Successfully");
            DisplayInventory();
            Clear();
            Con.close();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for Stock Quantity.");
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    }//GEN-LAST:event_UpdateItemBtnMouseClicked

    
