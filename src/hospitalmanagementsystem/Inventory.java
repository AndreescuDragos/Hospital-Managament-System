private void DisplayInventory() {
    try {
        Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");
        String Query = "SELECT * FROM inventory";
        St = Con.createStatement();
        Rs = St.executeQuery(Query);

        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("Item ID");
        model.addColumn("Item Name");
        model.addColumn("Item Type");
        model.addColumn("Stock Quantity");
        model.addColumn("Location");
        model.addColumn("Supplier");

        while (Rs.next()) {
            model.addRow(new Object[]{
                Rs.getInt("item_id"),
                Rs.getString("item_name"),
                Rs.getString("item_type"),
                Rs.getInt("stock_quantity"),
                Rs.getString("location"),
                Rs.getString("supplier")
            });
        }
        InventoryTable.setModel(model);

        Con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}

private void filterById() {
    String prefix = ItemIdTb.getText().trim();

    try {
        Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

        // Daca prefixul este gol, afisam tot
        if (prefix.isEmpty()) {
            DisplayInventory();
        } else {
            // Construim interogarea cu LIKE pentru a potrivi prefixul
            String query = "SELECT * FROM inventory WHERE CAST(item_id AS CHAR) LIKE ?";
            pst = Con.prepareStatement(query);
            pst.setString(1, prefix + "%"); // orice ID care începe cu prefix

            Rs = pst.executeQuery();

            // Construim un DefaultTableModel cu coloanele personalizate
            DefaultTableModel model = new DefaultTableModel();
            model.addColumn("Item ID");
            model.addColumn("Item Name");
            model.addColumn("Item Type");
            model.addColumn("Stock Quantity");
            model.addColumn("Location");
            model.addColumn("Supplier");

            // Adaugam randurile rezultate
            while (Rs.next()) {
                model.addRow(new Object[]{
                    Rs.getInt("item_id"),
                    Rs.getString("item_name"),
                    Rs.getString("item_type"),
                    Rs.getInt("stock_quantity"),
                    Rs.getString("location"),
                    Rs.getString("supplier")
                });
            }

            // Actualizam tabelul
            InventoryTable.setModel(model);
        }

        Con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}
    
