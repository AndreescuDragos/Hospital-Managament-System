    private void DeletePatientBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_DeletePatientBtnMouseClicked
        if (Key == 0) {
        JOptionPane.showMessageDialog(this, "Select a Patient to Delete");
    } else {
        try {
            // Conectare la baza de date
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

            // Pregatim interogarea pentru ștergere
            String Query = "DELETE FROM patients WHERE patient_id = ?";
            PreparedStatement Delete = Con.prepareStatement(Query);
            Delete.setInt(1, Key);

            // Executam ștergerea
            int row = Delete.executeUpdate();
            JOptionPane.showMessageDialog(this, "Patient Deleted Successfully");

            // Reimprospatam tabelul și golim campurile
            DisplayPatients();
            Clear();

            Con.close();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e);
        }
    }
    }//GEN-LAST:event_DeletePatientBtnMouseClicked

    private void UpdatePatientBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_UpdatePatientBtnMouseClicked
        if (Key == 0) {
        JOptionPane.showMessageDialog(this, "Select a Patient to Update");
    } else {
        try {
            // Validam daca patient_phone este un numar
            int patientPhone = Integer.parseInt(PPhoneTb.getText());

            // Conectare la baza de date
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

            // Pregatim interogarea pentru actualizare
            String Query = "UPDATE patients SET patient_name = ?, patient_phone = ?, patient_address = ?, patient_gender = ?, department = ? WHERE patient_id = ?";
            PreparedStatement Update = Con.prepareStatement(Query);
            Update.setString(1, PNameTb.getText());
            Update.setInt(2, patientPhone);
            Update.setString(3, PAddressTb.getText());
            Update.setString(4, PGenderCb.getSelectedItem().toString());
            Update.setString(5, PDepartmentCb.getSelectedItem().toString());
            Update.setInt(6, Key);

            int row = Update.executeUpdate();
            JOptionPane.showMessageDialog(this, "Patient Updated Successfully");

            DisplayPatients();
            Clear();

            Con.close();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for Phone.");
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e);
        }
    }
    }//GEN-LAST:event_UpdatePatientBtnMouseClicked

