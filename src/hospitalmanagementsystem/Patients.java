    private void AddPatientBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AddPatientBtnMouseClicked
        if (PIdTb.getText().isEmpty() || PNameTb.getText().isEmpty() || PPhoneTb.getText().isEmpty() || PAddressTb.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Missing Information");
    } else {
        try {
            boolean isPatientIdValid = true;
            boolean isPatientNameValid = true;
            boolean isPatientPhoneValid = true;

            int patientId = 0;
            int patientPhone = 0;
            String patientName = PNameTb.getText();

            // Validare pentru Patient ID
            try {
                patientId = Integer.parseInt(PIdTb.getText());
            } catch (NumberFormatException e) {
                isPatientIdValid = false;
            }

            // Validare pentru Patient Phone
            try {
                patientPhone = Integer.parseInt(PPhoneTb.getText());
            } catch (NumberFormatException e) {
                isPatientPhoneValid = false;
            }

            // Validare pentru Patient Name 
            if (!patientName.matches("[a-zA-Z ]+")) {
                isPatientNameValid = false;
            }

            // Mesaje de eroare pentru campurile invalide
            if (!isPatientIdValid && !isPatientPhoneValid && !isPatientNameValid) {
                JOptionPane.showMessageDialog(this, "Please enter valid values for Patient ID, Name, and Phone.");
                return;
            } else if (!isPatientIdValid && !isPatientPhoneValid) {
                JOptionPane.showMessageDialog(this, "Please enter valid numbers for Patient ID and Phone.");
                return;
            } else if (!isPatientIdValid && !isPatientNameValid) {
                JOptionPane.showMessageDialog(this, "Patient ID should be a valid number and Patient Name should only contain letters.");
                return;
            } else if (!isPatientPhoneValid && !isPatientNameValid) {
                JOptionPane.showMessageDialog(this, "Patient Phone should be a valid number and Patient Name should only contain letters.");
                return;
            } else if (!isPatientIdValid) {
                JOptionPane.showMessageDialog(this, "Please enter a valid number for Patient ID.");
                return;
            } else if (!isPatientPhoneValid) {
                JOptionPane.showMessageDialog(this, "Please enter a valid number for Patient Phone.");
                return;
            } else if (!isPatientNameValid) {
                JOptionPane.showMessageDialog(this, "Patient Name should only contain letters.");
                return;
            }

            // Conectare la baza de date
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

            // Verificam daca pacientul exista deja
            String CheckQuery = "SELECT * FROM patients WHERE patient_id = ?";
            PreparedStatement CheckStmt = Con.prepareStatement(CheckQuery);
            CheckStmt.setInt(1, patientId);
            ResultSet RsCheck = CheckStmt.executeQuery();

            if (RsCheck.next()) {
                // Pacientul exista deja
                JOptionPane.showMessageDialog(this, "This patient already exists. Use the Update Patient button to modify details.");
            } else {
                // Pacientul nu exista, adaugam unul nou
                String Query = "INSERT INTO patients (patient_id, patient_name, patient_phone, patient_address, patient_gender, department) VALUES (?, ?, ?, ?, ?, ?)";
                PreparedStatement Add = Con.prepareStatement(Query);
                Add.setInt(1, patientId);
                Add.setString(2, PNameTb.getText());
                Add.setInt(3, patientPhone);
                Add.setString(4, PAddressTb.getText());
                Add.setString(5, PGenderCb.getSelectedItem().toString());
                Add.setString(6, PDepartmentCb.getSelectedItem().toString());

                int row = Add.executeUpdate();
                JOptionPane.showMessageDialog(this, "Patient Added Successfully");

                // Reimprospatam tabelul și golim campurile
                DisplayPatients();
                Clear();
            }

            Con.close();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e);
        }
    }
    }//GEN-LAST:event_AddPatientBtnMouseClicked

