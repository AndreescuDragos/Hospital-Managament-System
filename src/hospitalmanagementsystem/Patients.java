    private void DisplayPatients() {
    try {
        Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");
        St = Con.createStatement();
        Rs = St.executeQuery("SELECT * FROM patients");

        // Definim un model de tabel cu anteturi personalizate
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new String[]{"Patient ID", "Patient Name", "Patient Phone", "Patient Address", "Gender", "Department"});

        // Adaugam randurile din ResultSet
        while (Rs.next()) {
            model.addRow(new Object[]{
                Rs.getInt("patient_id"),
                Rs.getString("patient_name"),
                Rs.getInt("patient_phone"),
                Rs.getString("patient_address"),
                Rs.getString("patient_gender"),
                Rs.getString("department")
            });
        }

        // Setam modelul în tabel
        PatientsTable.setModel(model);
        Con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}

    private void filterById() {
    String prefix = PIdTb.getText().trim();

    try {
        Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

        // Daca prefixul este gol, afisam tot
        if (prefix.isEmpty()) {
            DisplayPatients();
        } else {
            // Construim interogarea cu LIKE pentru a potrivi prefixul
            String query = "SELECT * FROM patients WHERE CAST(patient_id AS CHAR) LIKE ?";
            pst = Con.prepareStatement(query);
            pst.setString(1, prefix + "%"); // orice ID care începe cu prefix

            Rs = pst.executeQuery();

            // Construim un DefaultTableModel cu coloanele personalizate
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{"Patient ID", "Patient Name", "Patient Phone", "Patient Address", "Gender", "Department"});

            // Adaugam randurile rezultate
            while (Rs.next()) {
                model.addRow(new Object[]{
                Rs.getInt("patient_id"),
                Rs.getString("patient_name"),
                Rs.getInt("patient_phone"),
                Rs.getString("patient_address"),
                Rs.getString("patient_gender"),
                Rs.getString("department")
                });
            }

            // Actualizam tabelul
            PatientsTable.setModel(model);
        }

        Con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}
    
    
