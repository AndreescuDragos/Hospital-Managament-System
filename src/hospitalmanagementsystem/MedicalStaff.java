private void DisplayMedicalStaff(){ 
    try {
        Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");
        St = Con.createStatement();
        Rs = St.executeQuery("SELECT * FROM medical_staff");

        // Definirea modelului de tabel cu anteturi personalizate
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new String[]{"Employee ID", "Employee Name", "Employee Phone", "Employee Address", "Position", "Department"});

        // Adaugam randurile din ResultSet
        while (Rs.next()) {
            model.addRow(new Object[]{
                Rs.getInt("employee_id"),
                Rs.getString("employee_name"),
                Rs.getInt("employee_phone"),
                Rs.getString("employee_address"),
                Rs.getString("employee_position"),
                Rs.getString("department")
            });
        }

        // Setam modelul in tabel
        MedicalStaffTable.setModel(model);
        Con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}

private void filterById() {
    String prefix = EIdTb.getText().trim();

    try {
        Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

        // Daca prefixul este gol, afisam tot
        if (prefix.isEmpty()) {
            DisplayMedicalStaff();
        } else {
            // Construim interogarea cu LIKE pentru a potrivi prefixul
            String query = "SELECT * FROM medical_staff WHERE CAST(employee_id AS CHAR) LIKE ?";
            pst = Con.prepareStatement(query);
            pst.setString(1, prefix + "%"); // orice ID care începe cu prefix

            Rs = pst.executeQuery();

            // Construim un DefaultTableModel cu coloanele personalizate
            DefaultTableModel model = new DefaultTableModel();
            model.setColumnIdentifiers(new String[]{
                    "Employee ID",
                    "Employee Name",
                    "Employee Phone",
                    "Employee Address",
                    "Position",
                    "Department"
            });

            // Adaugam randurile rezultate
            while (Rs.next()) {
                model.addRow(new Object[]{
                        Rs.getInt("employee_id"),
                        Rs.getString("employee_name"),
                        Rs.getInt("employee_phone"),
                        Rs.getString("employee_address"),
                        Rs.getString("employee_position"),
                        Rs.getString("department")
                });
            }

            // Actualizam tabelul
            MedicalStaffTable.setModel(model);
        }

        Con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}

