    private void AddMedBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AddMedBtnMouseClicked
    if (EIdTb.getText().isEmpty() || ENameTb.getText().isEmpty() || EPhoneTb.getText().isEmpty() || EAddressTb.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Missing Information");
    } else {
        try {
            boolean isEmployeeIdValid = true;
            boolean isEmployeeNameValid = true;
            boolean isEmployeePhoneValid = true;
            
            int employeeId = 0;
            int employeePhone = 0;
            String employeeName = ENameTb.getText();

            // Validare pentru Employee ID
            try {
                employeeId = Integer.parseInt(EIdTb.getText());
            } catch (NumberFormatException e) {
                isEmployeeIdValid = false;
            }

            // Validare pentru Employee Phone
            try {
                employeePhone = Integer.parseInt(EPhoneTb.getText());
            } catch (NumberFormatException e) {
                isEmployeePhoneValid = false;
            }

            // Validare pentru Employee Name (verificare daca sunt doar litere)
            if (!employeeName.matches("[a-zA-Z ]+")) {
                isEmployeeNameValid = false;
            }

            // Mesaje de eroare pentru campurile invalide
            if (!isEmployeeIdValid && !isEmployeePhoneValid && !isEmployeeNameValid) {
                JOptionPane.showMessageDialog(this, "Please enter valid values for Employee ID, Name, and Phone.");
                return;
            } else if (!isEmployeeIdValid && !isEmployeePhoneValid) {
                JOptionPane.showMessageDialog(this, "Please enter valid numbers for Employee ID and Phone.");
                return;
            } else if (!isEmployeeIdValid && !isEmployeeNameValid) {
                JOptionPane.showMessageDialog(this, "Employee ID should be a valid number and Employee Name should only contain letters.");
                return;
            } else if (!isEmployeePhoneValid && !isEmployeeNameValid) {
                JOptionPane.showMessageDialog(this, "Employee Phone should be a valid number and Employee Name should only contain letters.");
                return;
            } else if (!isEmployeeIdValid) {
                JOptionPane.showMessageDialog(this, "Please enter a valid number for Employee ID.");
                return;
            } else if (!isEmployeePhoneValid) {
                JOptionPane.showMessageDialog(this, "Please enter a valid number for Employee Phone.");
                return;
            } else if (!isEmployeeNameValid) {
                JOptionPane.showMessageDialog(this, "Employee Name should only contain letters.");
                return;
            }

            // Conectare la baza de date
            Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

            // Verificam daca angajatul exista deja
            String CheckQuery = "SELECT * FROM medical_staff WHERE employee_id = ?";
            PreparedStatement CheckStmt = Con.prepareStatement(CheckQuery);
            CheckStmt.setInt(1, employeeId);
            ResultSet RsCheck = CheckStmt.executeQuery();

            if (RsCheck.next()) {
                // Angajatul exista deja
                JOptionPane.showMessageDialog(this, "This staff member already exists. Use the Update Staff button to modify details.");
            } else {
                // Angajatul nu exista, adaugam unul nou
                String Query = "INSERT INTO medical_staff (employee_id, employee_name, employee_phone, employee_address, employee_position, department) VALUES (?, ?, ?, ?, ?, ?)";
                PreparedStatement Add = Con.prepareStatement(Query);
                Add.setInt(1, employeeId);
                Add.setString(2, ENameTb.getText());
                Add.setInt(3, employeePhone);
                Add.setString(4, EAddressTb.getText());
                Add.setString(5, EPositionCb.getSelectedItem().toString());
                Add.setString(6, EDepartmentCb.getSelectedItem().toString());

                int row = Add.executeUpdate();
                JOptionPane.showMessageDialog(this, "Medical Staff Added Successfully");

                // Reimprospatam tabelul și golim campurile
                DisplayMedicalStaff();
                Clear();
            }

            Con.close();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_AddMedBtnMouseClicked
 }
    
