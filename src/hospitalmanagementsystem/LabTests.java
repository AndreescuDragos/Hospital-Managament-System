    private void LabTestsTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_LabTestsTableMouseClicked
        DefaultTableModel model = (DefaultTableModel) LabTestsTable.getModel();
        int MyIndex = LabTestsTable.getSelectedRow();

        // Preluarea datele din randul selectat
        TIdTb.setText(model.getValueAt(MyIndex, 0).toString()); // Test ID
        TNameCb.setSelectedItem(model.getValueAt(MyIndex, 2).toString()); // Test Name
        TDepartmentCb.setSelectedItem(model.getValueAt(MyIndex, 3).toString()); // Department
        TStatusCb.setSelectedItem(model.getValueAt(MyIndex, 6).toString()); // Test Status

        int patientId = Integer.parseInt(model.getValueAt(MyIndex, 1).toString()); // Patient ID
        int doctorId = Integer.parseInt(model.getValueAt(MyIndex, 4).toString()); // Doctor ID
        int technicianId = Integer.parseInt(model.getValueAt(MyIndex, 5).toString()); // Technician ID

        // Selectarea pacientul in tabelul PatientsTable
        for (int i = 0; i < PatientsTable.getRowCount(); i++) {
            if (Integer.parseInt(PatientsTable.getValueAt(i, 0).toString()) == patientId) {
                PatientsTable.setRowSelectionInterval(i, i);
                break;
            }
        }

        // Selectarea doctorul în tabelul DoctorsTable
        for (int i = 0; i < DoctorsTable.getRowCount(); i++) {
            if (Integer.parseInt(DoctorsTable.getValueAt(i, 0).toString()) == doctorId) {
                DoctorsTable.setRowSelectionInterval(i, i);
                break;
            }
        }

        // Selectam tehnicianul in tabelul TechniciansTable
        for (int i = 0; i < TechniciansTable.getRowCount(); i++) {
            if (Integer.parseInt(TechniciansTable.getValueAt(i, 0).toString()) == technicianId) {
                TechniciansTable.setRowSelectionInterval(i, i);
                break;
            }
        }
    }//GEN-LAST:event_LabTestsTableMouseClicked

