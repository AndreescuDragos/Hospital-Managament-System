    private void AddTestBtnMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AddTestBtnMouseClicked
        if (TIdTb.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Missing Information");
        } else {
            try {
                int testId = Integer.parseInt(TIdTb.getText());
                String patientId = PatientsTable.getValueAt(PatientsTable.getSelectedRow(), 0).toString();
                String doctorId = DoctorsTable.getValueAt(DoctorsTable.getSelectedRow(), 0).toString();
                String technicianId = TechniciansTable.getValueAt(TechniciansTable.getSelectedRow(), 0).toString();
                Con = DriverManager.getConnection("jdbc:mysql://localhost:3306/management_system", "root", "");

                String query = "SELECT * FROM lab_tests WHERE test_id = ?";
                pst = Con.prepareStatement(query);
                pst.setInt(1, testId);
                Rs = pst.executeQuery();
                if (Rs.next()) {
                    JOptionPane.showMessageDialog(this, "Test ID already exists. Please use Update instead.");
                } else {
                    String insertQuery = "INSERT INTO lab_tests (test_id, patient_id, test_name, department, employee1_id, employee2_id, status) VALUES (?, ?, ?, ?, ?, ?, ?)";
                    pst = Con.prepareStatement(insertQuery);
                    pst.setInt(1, testId);
                    pst.setInt(2, Integer.parseInt(patientId));
                    pst.setString(3, (String) TNameCb.getSelectedItem());
                    pst.setString(4, (String) TDepartmentCb.getSelectedItem());
                    pst.setInt(5, Integer.parseInt(doctorId));
                    pst.setInt(6, Integer.parseInt(technicianId));
                    pst.setString(7, (String) TStatusCb.getSelectedItem());
                    pst.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Test Added Successfully");
                    DisplayLabTests();
                    Clear();
                }
                Con.close();
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Please enter valid numeric values for Test ID.");
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_AddTestBtnMouseClicked

